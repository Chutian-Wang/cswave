def build(locale: str, mapping: dict[str, str]) -> None:
    tree = ET.parse(Path("translations") / "cswave_en.ts")
    root = tree.getroot()
    root.set("language", locale)
    for message in root.findall(".//message"):
        source = message.findtext("source") or ""
        translation = message.find("translation")
        if translation is None:
            translation = ET.SubElement(message, "translation")
        translation.text = mapping.get(source, source)
        translation.attrib.pop("type", None)
    ET.indent(tree, space="    ")
    tree.write(Path("translations") / f"cswave_{locale}.ts", encoding="utf-8", xml_declaration=True)


def main() -> None:
    for locale, mapping in TRANSLATIONS.items():
        build(locale, mapping)


if __name__ == "__main__":
    main()
